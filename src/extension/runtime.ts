function openDashboard() {
  if (currentWebviewPanel) {
    currentWebviewPanel.reveal(vscode.ViewColumn.One);
    currentWebviewPanel.webview.html = getWebviewContent();
    return;
  }

  currentWebviewPanel = vscode.window.createWebviewPanel(
    'agentGuardDashboard',
    'Agent Guard Supervisor',
    vscode.ViewColumn.One,
    { enableScripts: true, retainContextWhenHidden: true }
  );

  currentWebviewPanel.webview.html = getWebviewContent();

  currentWebviewPanel.webview.onDidReceiveMessage(message => {
    handleWebviewMessage(message);
  });

  currentWebviewPanel.onDidDispose(() => {
    currentWebviewPanel = null;
  });
}

function handleWebviewMessage(message) {
  const { command, payload } = message;

  if (command === 'refresh') {
    queryLiveQuota(true);
    updateStatusBar();
    refreshAllWebviews();
  } else if (command === 'toggleAwake') {
    toggleKeepAwake();
  } else if (command === 'acquireAwake') {
    acquireAwakeLease(payload);
  } else if (command === 'releaseAwake') {
    releaseAwakeLease();
  } else if (command === 'switchAccount') {
    showAccountPicker();
  } else if (command === 'snapshotAccount') {
    promptSnapshotAccount();
  } else if (command === 'importStockAuth') {
    const res = snapshotCurrentAccount(undefined, undefined);
    if (res.success) {
      vscode.window.showInformationMessage('✅ Agent Guard: Stock auth session cached for sign-in!');
    } else {
      vscode.window.showErrorMessage('Failed to cache stock auth: ' + res.message);
    }
  } else if (command === 'importStockAuthCustom') {
    const res = snapshotCurrentAccount(payload?.id, payload?.name);
    if (res.success) {
      vscode.window.showInformationMessage('✅ Agent Guard: Stock auth session cached for sign-in!');
    } else {
      vscode.window.showErrorMessage('Failed to cache stock auth: ' + res.message);
    }
  } else if (command === 'snapshotAccountCustom') {
    const res = snapshotCurrentAccount(payload?.id, payload?.name);
    if (res.success) {
      vscode.window.showInformationMessage('✅ Agent Guard: ' + res.message);
    } else {
      vscode.window.showErrorMessage('Failed to snapshot: ' + res.message);
    }
  } else if (command === 'addAccountDirect') {
    if (!payload?.id) {
      vscode.window.showWarningMessage('Please enter an account ID.');
    } else {
      const res = addAccountToPool(payload.id, payload.name, payload.token, undefined);
      if (res.success) {
        vscode.window.showInformationMessage('✅ Agent Guard: ' + res.message);
      } else {
        vscode.window.showErrorMessage('Failed to add: ' + res.message);
      }
    }
  } else if (command === 'addApiKeyDirect') {
    if (!payload?.id || !payload?.apiKey) {
      vscode.window.showWarningMessage('Please enter an account ID and API key.');
    } else {
      const res = addAccountToPool(payload.id, payload.name, undefined, payload.apiKey);
      if (res.success) {
        vscode.window.showInformationMessage('✅ Agent Guard: ' + res.message);
      } else {
        vscode.window.showErrorMessage('Failed to add: ' + res.message);
      }
    }
  } else if (command === 'selectAccount') {
    const res = switchAccount(payload, 'Switched via Webview Dashboard');
    if (res.success) {
      vscode.window.showInformationMessage('Switched to ' + res.targetName);
    }
  } else if (command === 'addAccount') {
    promptAddAccount();
  } else if (command === 'removeAccount') {
    const res = removeAccountFromPool(payload);
    if (res.success) {
      vscode.window.showInformationMessage(res.message);
    } else {
      vscode.window.showErrorMessage(res.message);
    }
  } else if (command === 'toggleAutoRotate') {
    setAutoRotateConfig(payload, undefined);
  } else if (command === 'setThreshold') {
    setAutoRotateConfig(undefined, payload);
    vscode.window.showInformationMessage('Auto-Switch threshold set to ' + payload + '%.');
  } else if (command === 'testTripwire') {
    triggerTestTripwire();
  } else if (command === 'manageGrants') {
    promptManageGrants();
  } else if (command === 'toggleGrant') {
    const auto = getAutoAcceptStatus();
    let tools = auto.tools || [];
    if (payload.enabled && !tools.includes(payload.tool)) {
      tools.push(payload.tool);
    } else if (!payload.enabled) {
      tools = tools.filter(t => t !== payload.tool);
    }
    setAutoAcceptGrants(tools);
  } else if (command === 'countCurrentFile') {
    countTokensInActiveEditor();
  } else if (command === 'selectModel') {
    activeModel = payload;
    updateStatusBar();
    refreshAllWebviews();
  } else if (command === 'resetTokenSession') {
    sessionTokens = { input: 0, output: 0, total: 0 };
    refreshAllWebviews();
    vscode.window.showInformationMessage('Token session reset.');
  } else if (command === 'installSkill') {
    installSkillDirectly(payload);
  } else if (command === 'runDoctor') {
    runDoctorDiagnostics();
  } else if (command === 'checkUpdate') {
    promptCheckForUpdates();
  } else if (command === 'performUpdate') {
    performAgentGuardUpdate();
  } else if (command === 'toggleStartupUpdate') {
    const cur = getAutoUpdateOnStartupConfig();
    setAutoUpdateOnStartupConfig(!cur);
    refreshAllWebviews();
    vscode.window.showInformationMessage('Startup Auto-Update is now ' + (!cur ? 'ENABLED' : 'DISABLED'));
  } else if (command === 'refreshMcp') {
    refreshAntigravityLsMcpDirect();
  } else if (command === 'copyMcpConfig') {
    copyMcpConfigToClipboard();
  } else if (command === 'autoApproveAllMcp') {
    setAutoAcceptGrants([...AGENT_GUARD_TOOLS]);
    refreshAllWebviews();
    vscode.window.showInformationMessage('⚡ Auto-Approved all 9 Agent Guard MCP tools!');
  }
}

function refreshAntigravityLsMcpDirect() {
  const address = process.env.ANTIGRAVITY_LS_ADDRESS || 'localhost:53416';
  const token = process.env.ANTIGRAVITY_CSRF_TOKEN || '';
  try {
    const tokenHeader = token ? ' -H "x-codeium-csrf-token: ' + token + '"' : '';
    const cmd = 'curl -sS -X POST "http://' + address + '/exa.language_server_pb.LanguageServerService/RefreshMcpServers" -H "Content-Type: application/json"' + tokenHeader + " -d '{}'";
    execSync(cmd, { timeout: 3000 });
    vscode.window.showInformationMessage('✅ Agent Guard: Reloaded MCP servers in Antigravity Language Server (all 9 tools active).');
  } catch {
    vscode.window.showInformationMessage('ℹ️ MCP schema files synced. Restart Language Server or Antigravity IDE to reload.');
  }
  refreshAllWebviews();
}

